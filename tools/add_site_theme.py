#!/usr/bin/env python3
"""Put the rating card, the theme switch and the scroll progress on every page.

Three additions, all idempotent by exact string match:

1. `theme-init.js`, an inline script in the head. It reads the stored theme and
   sets `data-theme` before the first paint. Without it, `theme.js` is deferred
   and a dark-mode visitor sees a white flash on every page change.
2. `<script defer src="/site/theme.js">` - the switch itself and the progress
   bar.
3. `<script defer src="/site/rating.js">` - but only on the calculator pages.
   A rating card on the privacy policy would be noise, and the count would
   never move. `CALC_PREFIX` decides which pages count as calculators.

The dark palette and the rating card's styles are appended to `style.css` by
`add_site_theme.py`, so this step only has to touch the markup.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / "public" / "site"
sys.path.insert(0, str(ROOT / "tools"))

MARKER = "<!-- ui -->"
CSS_MARKER = "/* ==== ui: dark palette + rating card (generated by add_site_theme.py) ==== */"

THEME_INIT = (
    MARKER
    + '<script>(function(){try{var t=localStorage.getItem("tm:theme");'
    'if(t!=="light"&&t!=="dark"){t=window.matchMedia("(prefers-color-scheme: dark)").matches?"dark":"light";}'
    'document.documentElement.setAttribute("data-theme",t);}catch(e){}})();</script>'
    '<script defer src="/site/theme.js"></script>'
)
RATING_SCRIPT = '<script defer src="/site/rating.js"></script>'

# Only the calculators carry the rating card. `url-map.json` is the site's own
# list of public URLs, so the card lands on exactly the pages a visitor reaches
# to use a tool, and the sitemap can never disagree with it.
def calculator_ids() -> set:
    mapping = json.loads((ROOT / "tools" / "url-map.json").read_text(encoding="utf-8"))
    ids = set()
    for clean, target in mapping.items():
        if target.startswith("/site/tools/"):
            ids.add(clean.strip("/"))
    return ids


def pages() -> list:
    found = [SITE / "index.html"]
    found += sorted(SITE.rglob("*.html"))
    return sorted(set(found))


def is_calculator(page: Path, ids: set) -> bool:
    return page.parent.name == "tools" and page.stem in ids


def write_css() -> None:
    """Append the dark palette and the rating card sheet to style.css.

    `style.css` is hand-maintained, so this only ever appends one marked block
    and replaces it on the next run. A generator that rewrote the file would
    throw away every hand edit above the marker.
    """
    from design import DARK_CSS, RATING_CSS

    sheet = SITE / "style.css"
    css = sheet.read_text(encoding="utf-8")
    block = CSS_MARKER + "\n" + DARK_CSS + "\n" + RATING_CSS
    if CSS_MARKER in css:
        css = css[: css.index(CSS_MARKER)].rstrip() + "\n" + block
    else:
        css = css.rstrip() + "\n\n" + block
    sheet.write_text(css, encoding="utf-8")
    print(f"style.css: dark palette + rating card written ({len(css)} bytes)")


def main() -> None:
    write_css()
    ids = calculator_ids()
    themed = rated = 0
    for page in pages():
        text = page.read_text(encoding="utf-8")
        new = text

        if MARKER not in new:
            new = new.replace("</head>", THEME_INIT + "</head>", 1)

        if is_calculator(page, ids) and RATING_SCRIPT not in new:
            new = new.replace("</body>", RATING_SCRIPT + "</body>", 1)

        if new != text:
            page.write_text(new, encoding="utf-8")
            themed += 1
            if RATING_SCRIPT in new and RATING_SCRIPT not in text:
                rated += 1

    print(f"theme + progress added to {themed} page(s); rating card on {rated} calculator(s)")


if __name__ == "__main__":
    main()
