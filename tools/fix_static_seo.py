#!/usr/bin/env python3
"""Fix the head of the static pages (home, blog, about, contact, privacy).

The SEO monitor flagged three things on pages that are not generated by a
script, so the fix has to be applied in place:

* `/` and `/about` had meta descriptions of 181 and 167 chars, past what Google
  renders (~160), so the snippet was cut mid-sentence;
* `/blog`, `/about`, `/contact` and `/privacy-policy` carried no structured
  data at all, which leaves the AI answer engines and Google guessing about
  what each page is;
* `/blog` is the hub the guides hang off, so it gets an ItemList of the posts
  plus a breadcrumb.

Re-running is safe: blocks written by this script are replaced, not duplicated.

    python3 tools/fix_static_seo.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "public" / "site"
BASE = "https://tankmetrics.in"
MARKER = "<!-- static-schema -->"

DESC = {
    "index.html": (
        "100 free, instant business calculators — EBITDA, valuation, LTV:CAC, "
        "burn rate, EMI and more. Built for founders, students and small "
        "business owners in India."
    ),
    "about.html": (
        "Tank Metrics is a free collection of 100 simple business calculators "
        "built for entrepreneurs, small business owners, students and "
        "first-time founders."
    ),
}
DESC_TAG = re.compile(r'<meta name="description" content="[^"]*">')
EXISTING = re.compile(re.escape(MARKER) + r".*?(?=</head>)", re.S)


def crumb(name: str, path: str) -> dict:
    return {
        "@context": "https://schema.org",
        "@type": "BreadcrumbList",
        "itemListElement": [
            {"@type": "ListItem", "position": 1, "name": "Home",
             "item": BASE + "/"},
            {"@type": "ListItem", "position": 2, "name": name,
             "item": f"{BASE}{path}"},
        ],
    }


def blog_item_list() -> dict:
    cards = re.findall(r'class="blog-card" href="([^"]+)"',
                       (SITE / "blog.html").read_text(encoding="utf-8"))
    items = []
    for i, href in enumerate(cards[:10], start=1):
        items.append({"@type": "ListItem", "position": i,
                      "url": f"{BASE}{href}"})
    return {
        "@context": "https://schema.org",
        "@type": "CollectionPage",
        "name": "Tank Metrics Blog",
        "url": f"{BASE}/blog",
        "inLanguage": "en-IN",
        "isPartOf": {"@type": "WebSite", "name": "Tank Metrics",
                     "url": BASE + "/"},
        "mainEntity": {"@type": "ItemList", "itemListElement": items},
    }


def blocks_for(fname: str) -> list[dict] | None:
    if fname == "blog.html":
        return [blog_item_list(), crumb("Blog", "/blog")]
    if fname == "about.html":
        return [crumb("About", "/about")]
    if fname == "contact.html":
        return [crumb("Contact", "/contact")]
    if fname == "privacy-policy.html":
        return [crumb("Privacy Policy", "/privacy-policy")]
    if fname == "terms-and-conditions.html":
        return [crumb("Terms and Conditions", "/terms-and-conditions")]
    if fname == "disclaimer.html":
        return [crumb("Disclaimer", "/disclaimer")]
    return None


def main() -> None:
    # 1. Descriptions first, so the schema reflects the final text.
    for fname, desc in DESC.items():
        f = SITE / fname
        t = f.read_text(encoding="utf-8")
        if len(desc) > 160:
            raise SystemExit(f"{fname}: description {len(desc)} chars is too long")
        t = DESC_TAG.sub(f'<meta name="description" content="{desc}">', t, count=1)
        f.write_text(t, encoding="utf-8")
        print(f"  description fixed: {fname} ({len(desc)} chars)")

    # 2. Structured data.
    for fname in ("blog.html", "about.html", "contact.html", "privacy-policy.html",
                  "terms-and-conditions.html", "disclaimer.html"):
        f = SITE / fname
        blocks = blocks_for(fname)
        if not blocks:
            continue
        t = f.read_text(encoding="utf-8")
        if MARKER in t:
            t = EXISTING.sub("", t)
        out = MARKER
        for b in blocks:
            out += ('<script type="application/ld+json">'
                    + json.dumps(b, ensure_ascii=False) + "</script>")
        t = t.replace("</head>", out + "</head>", 1)
        f.write_text(t, encoding="utf-8")
        print(f"  schema added: {fname} ({len(blocks)} block(s))")
    print("\ndone")


if __name__ == "__main__":
    main()
